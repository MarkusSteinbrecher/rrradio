#!/usr/bin/env node
/**
 * Pre-size every catalog favicon at build time so the iOS app stops
 * downsampling 256–1024px PNGs on device for a 38pt/64pt/76pt list cell
 * (rrradio#439). Reads `public/stations.json`, for each station with a
 * `favicon` field fetches the source bytes once, decodes them, emits
 * three downsampled WebP variants (76 / 128 / 152 px) under
 * `public/favicons/`, and rewrites the catalog to carry a `favicons`
 * object alongside the original `favicon` URL. The original `favicon`
 * stays put as the fallback for clients that don't pick the variants
 * (web app, custom user stations on iOS, Android until wired).
 *
 *   npm run favicon-variants
 *   npm run favicon-variants -- --dry-run
 *   npm run favicon-variants -- --only id1,id2
 *   npm run favicon-variants -- --local-only         # skip remote fetches
 *   npm run favicon-variants -- --limit 200          # cap candidate count
 *   npm run favicon-variants -- --concurrency 32     # parallel HTTP lanes
 *   npm run favicon-variants -- --force              # ignore cache, refetch all
 *   npm run favicon-variants -- --offline            # cache-only, never network
 *
 * Incremental: a JSON manifest at `public/favicons/manifest.json` records
 * the source URL + content hash + ETag per station. A second run with no
 * upstream changes:
 *   1. Skips entirely when the manifest entry + on-disk variants both
 *      exist and the catalog already references the current hashes.
 *   2. Otherwise issues a conditional GET (If-None-Match / If-Modified-Since)
 *      so unchanged favicons return 304 and we don't redecode.
 *
 * Variant filenames embed an 8-char source-content hash so CDN / browser
 * caches stay warm forever (`<id>-<size>-<hash>.webp`). When a favicon
 * changes upstream, the hash changes, the filename changes, and old
 * variants are pruned at the end of the run.
 *
 * Stations whose source can't be fetched (404, timeout, decode failure)
 * stay in the catalog without a `favicons` field — the client falls back
 * to the original on-device path.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

import sharp from 'sharp';

import { decodeIco, looksLikeIco } from './lib/ico-decode.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const PUBLIC_DIR = join(ROOT, 'public');
const CATALOG_PATH = join(PUBLIC_DIR, 'stations.json');
const VARIANTS_DIR = join(PUBLIC_DIR, 'favicons');
const MANIFEST_PATH = join(VARIANTS_DIR, 'manifest.json');

// iOS display sizes: 38pt @2x = 76, 64pt @2x = 128, 76pt @2x = 152.
// @3x devices downsample from 152 marginally per the issue's spec.
const VARIANT_SIZES = [76, 128, 152];
const DEFAULT_FETCH_TIMEOUT_MS = 15_000;
const MAX_BYTES = 4 * 1024 * 1024; // 4 MB cap on a single source favicon
const DEFAULT_CONCURRENCY = 8;
const MAX_RETRIES = 2; // 3 attempts total — long-tail RB hosts blip a lot
const RETRY_BASE_MS = 400;
const UA =
  'rrradio-favicon-pipeline/1.0 (+https://github.com/MarkusSteinbrecher/rrradio)';

// ─── args ────────────────────────────────────────────────────────────────
const argv = process.argv.slice(2);
const argFlag = (n) => argv.includes(n);
const argVal = (n, fb) => {
  const i = argv.indexOf(n);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fb;
};
const argList = (n) =>
  String(argVal(n, ''))
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);

const DRY_RUN = argFlag('--dry-run');
const FORCE = argFlag('--force');
const OFFLINE = argFlag('--offline') || process.env.RRRADIO_OFFLINE === '1';
const LOCAL_ONLY = argFlag('--local-only');
const ONLY = new Set(argList('--only'));
const VERBOSE = argFlag('--verbose');
const LIMIT = Number(argVal('--limit', 0)) || Infinity;
const CONCURRENCY = Math.max(
  1,
  Math.min(64, Number(argVal('--concurrency', DEFAULT_CONCURRENCY))),
);
const FETCH_TIMEOUT_MS = Math.max(
  1000,
  Number(argVal('--timeout', 0)) * 1000 || DEFAULT_FETCH_TIMEOUT_MS,
);

// ─── manifest IO ─────────────────────────────────────────────────────────
function loadManifest() {
  if (!existsSync(MANIFEST_PATH)) {
    return { $schema: 'generated by tools/build-favicon-variants.mjs', stations: {} };
  }
  try {
    const parsed = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
    if (!parsed || typeof parsed !== 'object' || !parsed.stations) {
      return { $schema: 'generated by tools/build-favicon-variants.mjs', stations: {} };
    }
    return parsed;
  } catch (e) {
    console.warn(`favicon-variants: manifest unreadable (${e.message}) — starting fresh`);
    return { $schema: 'generated by tools/build-favicon-variants.mjs', stations: {} };
  }
}

function saveManifest(m) {
  if (DRY_RUN) return;
  mkdirSync(VARIANTS_DIR, { recursive: true });
  const ordered = {
    $schema: m.$schema ?? 'generated by tools/build-favicon-variants.mjs',
    generatedAt: new Date().toISOString(),
    stations: Object.fromEntries(
      Object.entries(m.stations).sort(([a], [b]) => a.localeCompare(b)),
    ),
  };
  writeFileSync(MANIFEST_PATH, JSON.stringify(ordered, null, 2) + '\n');
}

// ─── catalog IO ──────────────────────────────────────────────────────────
function loadCatalog() {
  const parsed = JSON.parse(readFileSync(CATALOG_PATH, 'utf8'));
  const stations = Array.isArray(parsed) ? parsed : parsed.stations;
  if (!Array.isArray(stations)) {
    throw new Error('stations.json: stations[] not found');
  }
  return { parsed, stations };
}

function saveCatalog({ parsed, stations }) {
  if (DRY_RUN) return;
  const payload = Array.isArray(parsed) ? stations : { ...parsed, stations };
  writeFileSync(CATALOG_PATH, JSON.stringify(payload, null, 2) + '\n');
}

// ─── source URL resolution ───────────────────────────────────────────────
// `favicon: stations/grrif.png` is a path relative to public/; everything
// else is an absolute http(s) URL we must fetch over the network.
function resolveSource(station) {
  const fav = station.favicon;
  if (!fav || typeof fav !== 'string') return null;
  if (/^https?:\/\//i.test(fav)) return { kind: 'remote', url: fav };
  if (fav.startsWith('//')) return { kind: 'remote', url: `https:${fav}` };
  if (isAbsolute(fav)) return null; // shouldn't happen in our catalog
  // Local path under public/ — strip a possible leading slash.
  const rel = fav.replace(/^\/+/, '');
  return { kind: 'local', path: join(PUBLIC_DIR, rel), url: fav };
}

// ─── fetcher with timeout + conditional GET + retry ──────────────────────
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Retry transient failures (timeout, network error, 5xx, 429) with
// exponential back-off. Permanent failures (4xx, too-large) throw straight
// through so we don't waste attempts on a dead URL across 19k stations.
async function fetchSource(url, prevEntry) {
  if (OFFLINE) throw new Error('offline');
  let lastErr;
  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    if (attempt > 0) await sleep(RETRY_BASE_MS * 2 ** (attempt - 1));
    try {
      return await fetchOnce(url, prevEntry);
    } catch (e) {
      lastErr = e;
      if (!e.retryable) throw e;
    }
  }
  throw lastErr;
}

async function fetchOnce(url, prevEntry) {
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), FETCH_TIMEOUT_MS);
  const headers = { 'User-Agent': UA, Accept: 'image/*,*/*' };
  if (prevEntry?.etag) headers['If-None-Match'] = prevEntry.etag;
  if (prevEntry?.lastModified) headers['If-Modified-Since'] = prevEntry.lastModified;
  try {
    let res;
    try {
      res = await fetch(url, { signal: ctl.signal, redirect: 'follow', headers });
    } catch (e) {
      // Network-level failure (DNS, reset, timeout abort) — worth a retry.
      e.retryable = true;
      throw e;
    }
    if (res.status === 304) return { status: 304 };
    if (!res.ok) {
      const err = new Error(`HTTP ${res.status}`);
      err.retryable = res.status >= 500 || res.status === 429;
      throw err;
    }
    const len = Number(res.headers.get('content-length'));
    if (Number.isFinite(len) && len > MAX_BYTES) {
      throw new Error(`source too large: ${len} bytes > ${MAX_BYTES}`);
    }
    const reader = res.body?.getReader();
    if (!reader) {
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.length > MAX_BYTES) throw new Error(`source too large: ${buf.length} bytes`);
      return {
        status: 200,
        bytes: buf,
        etag: res.headers.get('etag') ?? undefined,
        lastModified: res.headers.get('last-modified') ?? undefined,
      };
    }
    const chunks = [];
    let total = 0;
    while (true) {
      const { value, done } = await reader.read();
      if (done) break;
      if (!value) continue;
      total += value.byteLength;
      if (total > MAX_BYTES) {
        try { await reader.cancel(); } catch { /* ignore */ }
        throw new Error(`source too large: >${MAX_BYTES} bytes`);
      }
      chunks.push(Buffer.from(value));
    }
    return {
      status: 200,
      bytes: Buffer.concat(chunks, total),
      etag: res.headers.get('etag') ?? undefined,
      lastModified: res.headers.get('last-modified') ?? undefined,
    };
  } finally {
    clearTimeout(timer);
  }
}

// ─── decode + downsample + encode ────────────────────────────────────────
async function generateVariants(bytes) {
  // Sharp decodes PNG/JPEG/WebP/GIF/SVG/TIFF/AVIF natively. ICO is the
  // notable miss — decode it ourselves into a PNG frame or raw RGBA first.
  let input = bytes;
  let inputOpts = { density: 384 /* for SVG inputs */ };
  if (looksLikeIco(bytes)) {
    const decoded = decodeIco(bytes);
    if (!decoded) {
      throw new Error('ICO frame not decodable (exotic compression/format)');
    }
    if (decoded.kind === 'png') {
      input = decoded.bytes;
    } else {
      input = decoded.data;
      inputOpts = {
        raw: { width: decoded.width, height: decoded.height, channels: decoded.channels },
      };
    }
  }
  const out = {};
  for (const size of VARIANT_SIZES) {
    // `fit: 'contain'` keeps the logo whole rather than cropping non-square
    // ones, with a transparent background so the cell shape comes through.
    const buf = await sharp(input, inputOpts)
      .resize(size, size, {
        fit: 'contain',
        background: { r: 0, g: 0, b: 0, alpha: 0 },
        withoutEnlargement: false,
      })
      .webp({ quality: 90, effort: 6, smartSubsample: true })
      .toBuffer();
    out[size] = buf;
  }
  return out;
}

// ─── variant naming + write ──────────────────────────────────────────────
function variantFilename(stationId, size, sourceHash) {
  return `${stationId}-${size}-${sourceHash.slice(0, 8)}.webp`;
}

function variantCatalogPath(filename) {
  // Relative to public/ — matches the existing `stations/<id>.png` convention.
  return `favicons/${filename}`;
}

function writeVariant(filename, buf) {
  if (DRY_RUN) return;
  mkdirSync(VARIANTS_DIR, { recursive: true });
  writeFileSync(join(VARIANTS_DIR, filename), buf);
}

function variantsExistOnDisk(stationId, sourceHash) {
  for (const size of VARIANT_SIZES) {
    const f = variantFilename(stationId, size, sourceHash);
    if (!existsSync(join(VARIANTS_DIR, f))) return false;
  }
  return true;
}

// ─── pool runner ─────────────────────────────────────────────────────────
async function runPool(items, concurrency, worker) {
  const results = new Array(items.length);
  let cursor = 0;
  const lanes = Array.from({ length: concurrency }, async () => {
    while (cursor < items.length) {
      const i = cursor++;
      results[i] = await worker(items[i], i);
    }
  });
  await Promise.all(lanes);
  return results;
}

// ─── main ────────────────────────────────────────────────────────────────
const t0 = Date.now();
const manifest = loadManifest();
const { parsed: catalogRaw, stations } = loadCatalog();

const allCandidates = stations
  .map((s) => ({ station: s, source: resolveSource(s) }))
  .filter(({ station, source }) => {
    if (!source) return false;
    if (ONLY.size > 0 && !ONLY.has(station.id)) return false;
    if (LOCAL_ONLY && source.kind !== 'local') return false;
    return true;
  });
const candidates = Number.isFinite(LIMIT) ? allCandidates.slice(0, LIMIT) : allCandidates;
const dropped = allCandidates.length - candidates.length;

console.log(
  `favicon-variants: ${candidates.length}/${allCandidates.length} station(s) with favicons` +
    (ONLY.size ? ` (filtered by --only)` : '') +
    (LOCAL_ONLY ? ' · LOCAL-ONLY' : '') +
    (dropped > 0 ? ` · LIMIT ${LIMIT} (${dropped} skipped)` : '') +
    (DRY_RUN ? ' · DRY RUN' : '') +
    (OFFLINE ? ' · OFFLINE' : '') +
    (FORCE ? ' · FORCE' : '') +
    ` · concurrency=${CONCURRENCY}`,
);

const counters = {
  cached: 0,         // manifest matched, variants on disk, catalog up-to-date
  notModified: 0,    // conditional GET returned 304
  regenerated: 0,    // bytes changed (or first run)
  unchangedBytes: 0, // refetched, bytes identical to manifest
  failed: 0,
  skippedNoFavicon: 0,
  unsupported: 0,
};
const failures = [];

await runPool(candidates, CONCURRENCY, async ({ station, source }, idx) => {
  const tag = `[${String(idx + 1).padStart(4)}/${candidates.length}] ${station.id}`;
  const prev = manifest.stations[station.id];
  const prevSourceUrl = prev?.sourceUrl;
  const prevHash = prev?.sourceHash;
  const prevVariants = prev?.variants;

  // Fast path: same source URL, manifest has hash, all on-disk variants
  // present. Apply variants to catalog (build-catalog.mjs wipes the
  // `favicons` field on every regenerate) and skip without touching the
  // network unless --force.
  if (
    !FORCE &&
    prevSourceUrl === source.url &&
    prevHash &&
    prevVariants &&
    VARIANT_SIZES.every((s) => prevVariants[s]) &&
    variantsExistOnDisk(station.id, prevHash)
  ) {
    applyVariantsToStation(station, prevVariants);
    counters.cached++;
    if (VERBOSE) console.log(`${tag} · cached`);
    return;
  }

  let bytes;
  let etag = prev?.etag;
  let lastModified = prev?.lastModified;
  try {
    if (source.kind === 'local') {
      if (!existsSync(source.path)) throw new Error(`local file missing: ${source.url}`);
      bytes = readFileSync(source.path);
    } else {
      // Prefer the conditional-GET path when we have prior validators and
      // the previous hash matched our on-disk variants.
      const sameUrl = prevSourceUrl === source.url;
      const reusable =
        sameUrl && prevHash && variantsExistOnDisk(station.id, prevHash) && !FORCE;
      const r = await fetchSource(source.url, reusable ? prev : null);
      if (r.status === 304) {
        // Upstream confirms unchanged — manifest stays, ensure catalog is wired.
        counters.notModified++;
        applyVariantsToStation(station, prevVariants);
        if (VERBOSE) console.log(`${tag} · 304`);
        // Refresh `lastFetched` so we know when we last validated.
        manifest.stations[station.id] = { ...prev, lastFetched: new Date().toISOString() };
        return;
      }
      bytes = r.bytes;
      etag = r.etag ?? prev?.etag;
      lastModified = r.lastModified ?? prev?.lastModified;
    }
  } catch (e) {
    counters.failed++;
    failures.push({ id: station.id, url: source.url, error: e.message });
    if (VERBOSE) console.log(`${tag} · fetch failed: ${e.message}`);
    // Leave the station's variants alone (drop them — the source we last
    // had is gone). Keep the original `favicon` field so the client falls
    // back to the on-device path.
    delete station.favicons;
    return;
  }

  const sourceHash = sha256(bytes);

  // If bytes are identical to last run, reuse on-disk variants verbatim.
  if (
    !FORCE &&
    sourceHash === prevHash &&
    variantsExistOnDisk(station.id, prevHash) &&
    prevVariants
  ) {
    counters.unchangedBytes++;
    applyVariantsToStation(station, prevVariants);
    manifest.stations[station.id] = {
      ...prev,
      sourceUrl: source.url,
      etag,
      lastModified,
      lastFetched: new Date().toISOString(),
    };
    if (VERBOSE) console.log(`${tag} · bytes match, reused`);
    return;
  }

  // Regenerate.
  let generated;
  try {
    generated = await generateVariants(bytes);
  } catch (e) {
    if (e.message.startsWith('ICO frame')) counters.unsupported++;
    else counters.failed++;
    failures.push({ id: station.id, url: source.url, error: e.message });
    if (VERBOSE) console.log(`${tag} · decode failed: ${e.message}`);
    delete station.favicons;
    return;
  }

  const variants = {};
  for (const size of VARIANT_SIZES) {
    const filename = variantFilename(station.id, size, sourceHash);
    writeVariant(filename, generated[size]);
    variants[size] = variantCatalogPath(filename);
  }
  applyVariantsToStation(station, variants);
  manifest.stations[station.id] = {
    sourceUrl: source.url,
    sourceHash,
    sourceLen: bytes.length,
    etag,
    lastModified,
    lastFetched: new Date().toISOString(),
    variants,
  };
  counters.regenerated++;
  if (VERBOSE) console.log(`${tag} · regenerated ${bytes.length}B → ${variantsByteSize(generated)}B`);
});

// Stations with no favicon at all — make sure the catalog doesn't carry a
// stale `favicons` field from a previous run.
for (const s of stations) {
  if (!resolveSource(s) && s.favicons) {
    delete s.favicons;
    counters.skippedNoFavicon++;
  }
  // Stations not in --only set keep whatever they had — leave them alone.
}

// Prune orphan variant files (referenced by no current manifest entry).
// Skip pruning on partial runs — the curator may be building up coverage
// across multiple sessions and we don't want to delete variants for
// stations we didn't even consider this pass.
const isFullRun = ONLY.size === 0 && !LOCAL_ONLY && candidates.length === allCandidates.length;
const referenced = new Set();
for (const entry of Object.values(manifest.stations)) {
  for (const v of Object.values(entry.variants ?? {})) {
    referenced.add(v.replace(/^favicons\//, ''));
  }
}
let pruned = 0;
if (isFullRun && existsSync(VARIANTS_DIR)) {
  for (const f of readdirSync(VARIANTS_DIR)) {
    if (f === 'manifest.json') continue;
    if (referenced.has(f)) continue;
    if (DRY_RUN) {
      pruned++;
      continue;
    }
    try {
      unlinkSync(join(VARIANTS_DIR, f));
      pruned++;
    } catch (e) {
      console.warn(`favicon-variants: failed to prune ${f}: ${e.message}`);
    }
  }
}

// Drop any manifest entry whose station no longer exists or no longer
// references a favicon — keeps the manifest from growing forever.
const liveIds = new Set(stations.map((s) => s.id));
for (const id of Object.keys(manifest.stations)) {
  if (!liveIds.has(id)) delete manifest.stations[id];
}

saveManifest(manifest);
saveCatalog({ parsed: catalogRaw, stations });

const elapsed = ((Date.now() - t0) / 1000).toFixed(1);
const totalVariantBytes = sumVariantBytesOnDisk();
console.log(
  `favicon-variants: ${counters.cached} cached, ${counters.notModified} 304, ` +
    `${counters.unchangedBytes} unchanged, ${counters.regenerated} regenerated, ` +
    `${counters.failed} failed, ${counters.unsupported} unsupported, ` +
    `${pruned} orphan(s) ${DRY_RUN ? 'would-be-' : ''}pruned ` +
    `(${(totalVariantBytes / (1024 * 1024)).toFixed(2)} MB total) ${elapsed}s`,
);
if (failures.length > 0) {
  const sample = failures.slice(0, 5).map((f) => `  · ${f.id}: ${f.error}`).join('\n');
  console.log(
    `favicon-variants: ${failures.length} station(s) without variants (fallback to original on device):\n${sample}` +
      (failures.length > 5 ? `\n  · …and ${failures.length - 5} more` : ''),
  );
}

// ─── helpers ─────────────────────────────────────────────────────────────
function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

function variantsByteSize(generated) {
  let n = 0;
  for (const buf of Object.values(generated)) n += buf.length;
  return n;
}

function sumVariantBytesOnDisk() {
  if (!existsSync(VARIANTS_DIR)) return 0;
  let n = 0;
  for (const f of readdirSync(VARIANTS_DIR)) {
    if (f === 'manifest.json') continue;
    try {
      n += statSync(join(VARIANTS_DIR, f)).size;
    } catch { /* ignore */ }
  }
  return n;
}

function applyVariantsToStation(station, variants) {
  if (!variants) {
    delete station.favicons;
    return;
  }
  const out = {};
  for (const size of VARIANT_SIZES) {
    if (variants[size]) out[size] = variants[size];
  }
  if (Object.keys(out).length === 0) {
    delete station.favicons;
  } else {
    station.favicons = out;
  }
}

