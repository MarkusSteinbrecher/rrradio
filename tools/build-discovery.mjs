/**
 * Build the Browse discovery summary → public/discovery.json.
 *
 * The discovery landing (genre chips, country chips, "Browse all N" count)
 * derives entirely from per-genre / per-country catalog counts. Computing
 * those client-side means waiting on the full 21 MB / 31k-station
 * stations.json before the landing can paint — the dominant cost of the
 * 2-3s mobile Browse load. This precomputes the counts into a ~few-KB file
 * the app fetches first, so the landing renders instantly; the full catalog
 * then loads in the background for search / filters / Browse-all.
 *
 * Genre matching reuses the SAME taxonomy + matcher the runtime uses
 * (../src/genre-taxonomy.data.mjs), so counts can't drift.
 *
 * Reads public/stations.json (built by build-catalog.mjs — run this after).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GENRES, stationMatchesGenre } from '../src/genre-taxonomy.data.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const stationsPath = join(root, 'public/stations.json');
const raw = JSON.parse(readFileSync(stationsPath, 'utf8'));
const stations = Array.isArray(raw.stations) ? raw.stations : [];

const genreCounts = new Map(GENRES.map((g) => [g.id, 0]));
const countryCounts = new Map();

for (const s of stations) {
  const code = (s.country ?? '').toUpperCase();
  if (code) countryCounts.set(code, (countryCounts.get(code) ?? 0) + 1);
  if (!Array.isArray(s.tags) || s.tags.length === 0) continue;
  for (const g of GENRES) {
    if (stationMatchesGenre(s, g)) genreCounts.set(g.id, genreCounts.get(g.id) + 1);
  }
}

// Genres in taxonomy order (genreChips re-sorts by count); only the ones
// with a positive count, to keep the file lean.
const genres = GENRES.map((g) => ({ id: g.id, count: genreCounts.get(g.id) ?? 0 })).filter(
  (g) => g.count > 0,
);
// Countries sorted by count desc then code (countryChips caps to its own
// limit at render time); ~200 entries, a few KB.
const countries = [...countryCounts.entries()]
  .map(([code, count]) => ({ code, count }))
  .sort((a, b) => b.count - a.count || a.code.localeCompare(b.code));

const payload = {
  $schema: 'generated by tools/build-discovery.mjs from public/stations.json',
  total: stations.length,
  genres,
  countries,
};

const outPath = join(root, 'public/discovery.json');
writeFileSync(outPath, JSON.stringify(payload) + '\n');

console.log(
  `discovery: ${stations.length} stations → public/discovery.json ` +
    `(${genres.length} genres, ${countries.length} countries)`,
);

// ─── Surprise me exclusions → public/surprise.json (#97) ───
// The "Surprise me" picker must never land on a known duplicate or a station
// whose stream last probed bad. Both signals live in multi-MB artifacts the
// app never downloads, so distil them here into a flat id list (~tens of KB,
// fetched lazily by src/surprise.ts):
//   · every non-primary member of a station-duplicates.json group (the
//     primary is the best-ranked published entry: curated status, featured,
//     stream healthy, logo, bitrate, then id);
//   · every published station whose `stream` health verdict is `bad`.
const readJson = (rel) => {
  const p = join(root, rel);
  if (!existsSync(p)) return null;
  try {
    return JSON.parse(readFileSync(p, 'utf8'));
  } catch {
    return null;
  }
};
const byId = new Map(stations.map((s) => [s.id, s]));
const health = readJson('public/station-health.json')?.stations ?? {};
const streamBad = (id) => health[id]?.stream?.v === 'bad';
const STATUS_RANK = { working: 0, 'icy-only': 1, 'stream-only': 2 };
const rank = (s) => [
  STATUS_RANK[s.status] ?? 3,
  s.featured ? 0 : 1,
  streamBad(s.id) ? 1 : 0,
  s.favicon ? 0 : 1,
  -(s.bitrate ?? 0),
];
const cmp = (a, b) => {
  const ra = rank(a);
  const rb = rank(b);
  for (let i = 0; i < ra.length; i++) if (ra[i] !== rb[i]) return ra[i] - rb[i];
  return a.id.localeCompare(b.id);
};

const exclude = new Set();
let dupExcluded = 0;
for (const group of readJson('public/station-duplicates.json')?.duplicateGroups ?? []) {
  const members = (group.entries ?? []).map((e) => byId.get(e.id)).filter(Boolean).sort(cmp);
  for (const s of members.slice(1)) {
    if (!exclude.has(s.id)) dupExcluded += 1;
    exclude.add(s.id);
  }
}
for (const s of stations) if (streamBad(s.id)) exclude.add(s.id);

const surpriseOut = join(root, 'public/surprise.json');
writeFileSync(
  surpriseOut,
  JSON.stringify({
    $schema:
      'generated by tools/build-discovery.mjs from station-duplicates.json + station-health.json',
    exclude: [...exclude].sort(),
  }) + '\n',
);
console.log(
  `discovery: ${exclude.size} surprise exclusions → public/surprise.json ` +
    `(${dupExcluded} duplicate, ${exclude.size - dupExcluded} stream-bad)`,
);
