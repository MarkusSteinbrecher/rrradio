/**
 * Build the Browse discovery summary → public/discovery.json.
 *
 * The discovery landing (genre chips, country chips, "Browse all N" count)
 * derives entirely from per-genre / per-country catalog counts. Computing
 * those client-side means waiting on the full 21 MB / 31k-station
 * stations.json before the landing can paint — the dominant cost of the
 * 2-3s mobile Browse load. This precomputes the counts into a ~few-KB file
 * the app fetches first, so the landing renders instantly; the full catalog
 * then loads in the background for search / filters / Browse-all.
 *
 * Genre matching reuses the SAME taxonomy + matcher the runtime uses
 * (../src/genre-taxonomy.data.mjs), so counts can't drift.
 *
 * Reads public/stations.json (built by build-catalog.mjs — run this after).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GENRES, stationMatchesGenre } from '../src/genre-taxonomy.data.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const stationsPath = join(root, 'public/stations.json');
const raw = JSON.parse(readFileSync(stationsPath, 'utf8'));
const stations = Array.isArray(raw.stations) ? raw.stations : [];

const genreCounts = new Map(GENRES.map((g) => [g.id, 0]));
const countryCounts = new Map();

for (const s of stations) {
  const code = (s.country ?? '').toUpperCase();
  if (code) countryCounts.set(code, (countryCounts.get(code) ?? 0) + 1);
  if (!Array.isArray(s.tags) || s.tags.length === 0) continue;
  for (const g of GENRES) {
    if (stationMatchesGenre(s, g)) genreCounts.set(g.id, genreCounts.get(g.id) + 1);
  }
}

// Genres in taxonomy order (genreChips re-sorts by count); only the ones
// with a positive count, to keep the file lean.
const genres = GENRES.map((g) => ({ id: g.id, count: genreCounts.get(g.id) ?? 0 })).filter(
  (g) => g.count > 0,
);
// Countries sorted by count desc then code (countryChips caps to its own
// limit at render time); ~200 entries, a few KB.
const countries = [...countryCounts.entries()]
  .map(([code, count]) => ({ code, count }))
  .sort((a, b) => b.count - a.count || a.code.localeCompare(b.code));

const payload = {
  $schema: 'generated by tools/build-discovery.mjs from public/stations.json',
  total: stations.length,
  genres,
  countries,
};

const outPath = join(root, 'public/discovery.json');
writeFileSync(outPath, JSON.stringify(payload) + '\n');

console.log(
  `discovery: ${stations.length} stations → public/discovery.json ` +
    `(${genres.length} genres, ${countries.length} countries)`,
);
