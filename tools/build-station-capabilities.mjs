#!/usr/bin/env node
/**
 * Build a native-client metadata capability manifest from an existing
 * station catalog and src/fetchers.json. Network-free by design.
 *
 *   npm run station-capabilities
 *   npm run station-capabilities -- --catalog public/stations-ios-local.json --out public/station-capabilities-ios-local.json
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, isAbsolute, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildStationCapabilitiesPayload } from './station-capabilities.mjs';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

function flag(name, fallback) {
  const prefix = `--${name}=`;
  const inline = process.argv.find((arg) => arg.startsWith(prefix));
  if (inline) return inline.slice(prefix.length);
  const idx = process.argv.indexOf(`--${name}`);
  if (idx >= 0 && idx + 1 < process.argv.length) return process.argv[idx + 1];
  return fallback;
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function rootPath(path) {
  return isAbsolute(path) ? path : join(ROOT, path);
}

function catalogStations(catalog) {
  const stations = Array.isArray(catalog) ? catalog : catalog?.stations;
  if (!Array.isArray(stations)) {
    throw new Error('catalog does not contain stations[]');
  }
  return stations;
}

export function writeStationCapabilities({
  catalogPath = join(ROOT, 'public/stations.json'),
  outPath = join(ROOT, 'public/station-capabilities.json'),
  schema = 'generated by tools/build-station-capabilities.mjs from public/stations.json + src/fetchers.json',
  generatedAt,
} = {}) {
  const fetcherManifestPath = join(ROOT, 'src/fetchers.json');
  const catalog = readJson(catalogPath);
  const fetcherManifest = readJson(fetcherManifestPath);
  const payload = buildStationCapabilitiesPayload(catalogStations(catalog), fetcherManifest, {
    schema,
    generatedAt,
    sourceCatalog: catalogPath.replace(`${ROOT}/`, ''),
    sourceManifest: fetcherManifestPath.replace(`${ROOT}/`, ''),
  });

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, JSON.stringify(payload, null, 2) + '\n');
  return payload;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const catalogPath = rootPath(flag('catalog', 'public/stations.json'));
  const outPath = rootPath(flag('out', 'public/station-capabilities.json'));
  const schema = flag(
    'schema',
    'generated by tools/build-station-capabilities.mjs from public/stations.json + src/fetchers.json',
  );
  const payload = writeStationCapabilities({ catalogPath, outPath, schema });
  console.log(
    `station-capabilities: ${payload.counts.stations} station(s) -> ${outPath.replace(`${ROOT}/`, '')}`,
  );
  console.log(`  api: ${payload.counts.byMetadataStrategy.api}`);
  console.log(`  icy: ${payload.counts.byMetadataStrategy.icy}`);
  console.log(`  hls: ${payload.counts.byMetadataStrategy.hls}`);
  console.log(`  none: ${payload.counts.byMetadataStrategy.none}`);
}
