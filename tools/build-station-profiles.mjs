#!/usr/bin/env node
/**
 * Compiles the rich station-knowledge base:
 *   data/station-profiles/<id>.yaml  →  public/station-profiles.json
 *
 * One human-authored YAML per station holds the deep, descriptive record
 * (identity, ownership, editorial profile, music incl. a real playlist
 * snapshot, programming, reach, streams, now-playing, presence). This is a
 * SEPARATE layer from the catalog: data/stations.yaml answers "what plays
 * this stream"; a station-profile answers "what IS this station" — for
 * cross-station analysis and the per-station detail page.
 *
 * The compiled public/station-profiles.json is a `{ count, profiles[] }`
 * payload sorted by id. No timestamp is baked in (keeps diffs clean).
 *
 * Field spec: data/station-profiles/README.md.
 *
 *   npm run station-profiles            # build
 *   node tools/build-station-profiles.mjs --check   # validate only, no write
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const SRC = join(root, 'data', 'station-profiles');
const OUT = join(root, 'public', 'station-profiles.json');
const CHECK_ONLY = process.argv.includes('--check');

const NOWPLAYING_TYPES = new Set([
  'icecast-xspf', 'status-json', 'graphql', 'azuracast', 'json', 'json-covers', 'icy', 'none',
]);
const ORG_TYPES = new Set(['public', 'commercial', 'community', 'internet']);
const ROTATION = new Set(['current-hits', 'gold', 'mixed', 'eclectic', 'freeform']);

function fail(errs) {
  for (const e of errs) console.error(`build-station-profiles: ${e}`);
  process.exit(1);
}

if (!existsSync(SRC)) fail([`missing source dir ${SRC}`]);

const files = readdirSync(SRC).filter((f) => f.endsWith('.yaml') && !f.startsWith('_'));
const errors = [];
const warnings = [];
const profiles = [];
const ids = new Set();

for (const f of files.sort()) {
  let p;
  try {
    p = parseYaml(readFileSync(join(SRC, f), 'utf8'));
  } catch (e) {
    errors.push(`${f}: YAML parse error — ${e.message}`);
    continue;
  }
  if (!p || typeof p !== 'object') { errors.push(`${f}: empty or not a mapping`); continue; }

  // hard requirements
  if (!p.id) errors.push(`${f}: missing id`);
  else if (`${p.id}.yaml` !== f) errors.push(`${f}: id "${p.id}" must match filename`);
  else if (ids.has(p.id)) errors.push(`${f}: duplicate id ${p.id}`);
  else ids.add(p.id);
  if (!p.identity?.name) errors.push(`${f}: missing identity.name`);

  // soft enum checks (warn — the data layer shouldn't block on taxonomy drift)
  if (p.organization?.type && !ORG_TYPES.has(p.organization.type))
    warnings.push(`${f}: organization.type "${p.organization.type}" not in {${[...ORG_TYPES].join(', ')}}`);
  if (p.music?.rotationStyle && !ROTATION.has(p.music.rotationStyle))
    warnings.push(`${f}: music.rotationStyle "${p.music.rotationStyle}" not in {${[...ROTATION].join(', ')}}`);
  if (p.nowPlaying?.type && !NOWPLAYING_TYPES.has(p.nowPlaying.type))
    warnings.push(`${f}: nowPlaying.type "${p.nowPlaying.type}" not in {${[...NOWPLAYING_TYPES].join(', ')}}`);
  if (Array.isArray(p.streams)) {
    for (const s of p.streams) {
      if (s.url && !/^https:\/\//.test(s.url)) warnings.push(`${f}: stream not https — ${s.url}`);
    }
  }

  if (p.id) profiles.push(p);
}

if (errors.length) fail(errors);
for (const w of warnings) console.warn(`build-station-profiles: warn: ${w}`);

profiles.sort((a, b) => a.id.localeCompare(b.id));
const payload = {
  $schema: 'generated by tools/build-station-profiles.mjs from data/station-profiles/*.yaml — see data/station-profiles/README.md',
  count: profiles.length,
  profiles,
};

if (CHECK_ONLY) {
  console.log(`build-station-profiles: ${profiles.length} profile(s) valid (--check, no write) · ${warnings.length} warning(s)`);
  process.exit(0);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, JSON.stringify(payload, null, 2) + '\n');
console.log(`build-station-profiles: ${profiles.length} profile(s) → public/station-profiles.json · ${warnings.length} warning(s)`);
